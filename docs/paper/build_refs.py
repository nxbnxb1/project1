"""Write the \\bibitem list of a manuscript in order of first citation.

Usage: python3 docs/paper/build_refs.py docs/paper/vi/manuscript_vi.tex docs/paper/vi/refs_auto.tex
       python3 docs/paper/build_refs.py docs/paper/en/manuscript.tex --inline
With --inline the list replaces the lines between '% BEGIN AUTO REFS' and '% END AUTO REFS' of the manuscript
itself (the Springer Nature template asks for a single .tex file).
Keys come from docs/paper/references.py; an unknown key stops the build, unused entries are listed.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from references import REFS  # noqa: E402

src, out = sys.argv[1], sys.argv[2]
text = open(src, encoding='utf-8').read()
text = re.sub(r'(?<!\\)%.*', '', text)
order = []
for grp in re.findall(r'\\cite\{([^}]*)\}', text):
    for k in (x.strip() for x in grp.split(',')):
        if k and k not in order:
            order.append(k)
missing = [k for k in order if k not in REFS]
if missing:
    sys.exit('unknown reference keys: ' + ', '.join(missing))
items = ''.join(f'\\bibitem{{{k}}} {REFS[k]}\n\n' for k in order)
if out == '--inline':
    full = open(src, encoding='utf-8').read()
    m = re.search(r'(% BEGIN AUTO REFS[^\n]*\n).*?(% END AUTO REFS)', full, re.S)
    if not m:
        sys.exit('markers % BEGIN AUTO REFS / % END AUTO REFS not found')
    full = full[:m.end(1)] + items + full[m.start(2):]
    with open(src, 'w', encoding='utf-8') as f:
        f.write(full)
    out = src
else:
    with open(out, 'w', encoding='utf-8') as f:
        f.write('% generated by docs/paper/build_refs.py - do not edit\n' + items)
print(f'{len(order)} references written to {out}')
unused = [k for k in REFS if k not in order]
if unused:
    print('not cited:', ', '.join(unused))
